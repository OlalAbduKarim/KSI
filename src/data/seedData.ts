function clamp(num: number, min: number, max: number): number {
  return Math.max(min, Math.min(max, Math.round(num * 10) / 10));
}

function generateTermSeries(bp: SchoolBlueprint, idx: number): TermRecord[] {
  const records: TermRecord[] = [];
  // Term deltas based on profile
  const termOffsets: Record<
    SchoolBlueprint['profile'],
    { pass: [number, number, number]; att: [number, number, number]; enrol: [number, number, number] }
  > = {
    high: { pass: [-2, -1, 0], att: [-1, 0, 0], enrol: [-24, -10, 0] },
    moderate: { pass: [-1, 1, 0], att: [1, 0, 0], enrol: [-12, -5, 0] },
    underperforming: { pass: [9, 4, 0], att: [10, 5, 0], enrol: [28, 12, 0] },
    declining_att: { pass: [6, 3, 0], att: [11, 6, 0], enrol: [15, 8, 0] },
    improving_exam: { pass: [-16, -8, 0], att: [-8, -4, 0], enrol: [-30, -14, 0] },
    staff_shortage: { pass: [4, 2, 0], att: [3, 1, 0], enrol: [-45, -18, 0] },
    poor_sanitation: { pass: [3, 1, 0], att: [6, 3, 0], enrol: [10, 4, 0] },
    critical_infra: { pass: [5, 2, 0], att: [4, 2, 0], enrol: [18, 8, 0] },
    successful_intervention: { pass: [-19, -9, 0], att: [-15, -7, 0], enrol: [-20, -8, 0] },
  };

  const offset = termOffsets[bp.profile];

  VALID_TERMS.forEach((term: ReportingTerm, tIdx: number) => {
    const enrolment = Math.max(180, bp.baseEnrolment + offset.enrol[tIdx]);
    const femaleRatio = 0.51 + ((idx % 5) - 2) * 0.01;
    const female = Math.round(enrolment * femaleRatio);
    const male = enrolment - female;
    const passRate = clamp(bp.basePass + offset.pass[tIdx], 28, 97);
    const attRate = clamp(bp.baseAttendance + offset.att[tIdx], 52, 98);
    const teacherAtt = clamp(attRate + 6 + (idx % 4), 72, 99);
    const chronicAbs = clamp(Math.max(2, (100 - attRate) * 0.52), 1.5, 32);

    const mathScore = clamp(passRate - 4 + (idx % 5), 25, 97);
    const englishScore = clamp(passRate + 3 - (idx % 4), 30, 98);
    const scienceScore = clamp(passRate - 2 + ((idx + 1) % 5), 25, 97);

    const teachers =
      tIdx === 0 && bp.profile === 'staff_shortage'
        ? bp.baseTeachers + 3
        : bp.baseTeachers;

    const deskPct =
      bp.classroomCond === 'Good'
        ? 95 - (idx % 4)
        : bp.classroomCond === 'Fair'
        ? 78 - (idx % 7)
        : bp.classroomCond === 'Poor'
        ? 61 - (idx % 6)
        : 46 - (idx % 5);

    const verificationStatus: TermRecord['verificationStatus'] =
      tIdx < 2
        ? 'Verified'
        : bp.term2Status === 'Approved'
        ? 'Verified'
        : bp.term2Status === 'Submitted' || bp.term2Status === 'Under Review'
        ? 'Pending Review'
        : 'Unverified';

    records.push({
      id: `REC-${bp.id}-${tIdx + 1}`,
      schoolId: bp.id,
      term,
      verificationStatus,
      updatedAt:
        tIdx === 0 ? '2025-11-28' : tIdx === 1 ? '2026-04-17' : '2026-10-28',
      overallPassRate: passRate,
      mathScore,
      englishScore,
      scienceScore,
      examParticipationRate: clamp(attRate + 4, 68, 99.5),
      totalEnrolment: enrolment,
      maleEnrolment: male,
      femaleEnrolment: female,
      newAdmissions: 22 + ((idx * 7 + tIdx * 5) % 48),
      withdrawals: bp.profile === 'underperforming' || bp.profile === 'declining_att' ? 18 + (idx % 10) : 4 + (idx % 6),
      learnerAttendanceRate: attRate,
      teacherAttendanceRate: teacherAtt,
      chronicAbsenteeismRate: chronicAbs,
      totalTeachers: teachers,
      qualifiedTeachersPct: bp.ownership === 'Government' ? 92 + (idx % 7) : 84 + (idx % 12),
      teacherVacancies:
        bp.profile === 'staff_shortage'
          ? 5
          : bp.profile === 'underperforming'
          ? 4
          : idx % 3,
      staffTurnoverCount: bp.profile === 'staff_shortage' ? 3 : idx % 2,
      classroomsCount: Math.max(8, Math.round(enrolment / (bp.classroomCond === 'Critical' ? 68 : 44))),
      classroomCondition: bp.classroomCond,
      deskAvailabilityPct: deskPct,
      toiletCondition: bp.toiletCond,
      waterAvailable: bp.water,
      electricityAvailable: bp.electricity,
      accessibilityFacilities: bp.accessibility,
      firstAidAvailable: bp.firstAid,
      sanitationRating: bp.sanitation,
      safetyInspectionStatus: bp.safetyStatus,
      safetyIncidentsCount:
        bp.safetyStatus === 'Failed' ? 3 + (idx % 3) : bp.safetyStatus === 'Pending' ? 1 : 0,
      safeguardingReferralStatus: bp.safeguarding,
      feeCollectionRate:
        bp.ownership === 'Private' ? clamp(78 - (bp.profile === 'underperforming' ? 18 : 0) + (idx % 12), 45, 97) : null,
      learningMaterialAvailability: bp.materials,
      resourceConstraints:
        bp.materials === 'Scarce'
          ? 'Critical shortage of core textbooks and teacher guides.'
          : bp.materials === 'Partial'
          ? 'Supplementary science kits and revision booklets needed.'
          : 'Core instructional materials stocked within standard ratios.',
      operationalChallenges: bp.challenge,
    });
  });

  return records;
}

